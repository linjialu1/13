def sha(p: Path) -> str:
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


# ---------------------------------------------------------------- S2 asset reuse (0 new fits)
def s2_boundary_dir(s2_root: Path, dataset: str, seed: int, task: int) -> Path:
    return Path(s2_root) / dataset / f"seed{seed}" / f"task{task}"


def load_s2_readout_asset(s2_root: Path, dataset: str, seed: int, task: int) -> dict:
    """Load the accepted D1 (identity) and D3 (PCA16) transforms + ridge W/b.

    Returns arrays plus the source file hashes so the run ledger can bind them.
    No fitting happens here: these were produced and sealed by S2.
    """
    bdir = s2_boundary_dir(s2_root, dataset, seed, task)
    probs = np.load(bdir / "probes.npz")
    tf = np.load(bdir / "transforms.npz")
    out = {
        "D1_W": probs["D1_joint56__W"], "D1_b": probs["D1_joint56__b"],
        "D3_W": probs["D3_pca16__W"], "D3_b": probs["D3_pca16__b"],
        "D3_mean": tf["D3_pca16__mean"], "D3_components": tf["D3_pca16__components"],
        "source_hashes": {"probes.npz": sha(bdir / "probes.npz"),
                          "transforms.npz": sha(bdir / "transforms.npz")},
        "reused_not_refit": True,
    }
    if out["D1_W"].shape[0] != JOINT_DIM:
        raise ValueError("D1 W does not have 56 rows — wrong asset")
    if out["D3_W"].shape[0] != PCA_DIM:
        raise ValueError("D3 W does not have 16 rows — wrong asset")
    return out


def apply_pca_after_pseudo(common_joint: np.ndarray, mean: np.ndarray,
                           components: np.ndarray) -> np.ndarray:
    """Ordering guard: PCA is applied to the assembled joint-space matrix.

    `common_joint` must already contain real rows AND pseudo rows generated in the
    original 56-dim joint space.  Raises if a projected (16-dim) matrix is passed,
    which would mean the ordering was inverted upstream.
    """
    X = np.asarray(common_joint)
    if X.ndim != 2 or X.shape[1] != JOINT_DIM:
        raise ValueError(f"expected joint-space matrix with {JOINT_DIM} columns, "
                         f"got {X.shape}")
    if np.asarray(mean).shape != (JOINT_DIM,) or np.asarray(components).shape != (JOINT_DIM, PCA_DIM):
        raise ValueError("PCA parameters do not match joint space")
    return (X.astype(np.float64) - mean) @ components


def ridge_predict(W: np.ndarray, b: np.ndarray, X: np.ndarray,
                  seen: list[int]) -> tuple[np.ndarray, np.ndarray]:
    """Predictions from a SAVED ridge solution (no fitting)."""
    X = np.asarray(X, dtype=np.float64)
    if X.shape[1] != W.shape[0]:
        raise ValueError(f"feature dim {X.shape[1]} != W rows {W.shape[0]}")
    logits = X @ W + b
    idx = logits.argmax(axis=1)                     # ties -> smallest index
    return logits, np.asarray([seen[i] for i in idx], dtype=np.int64)


def macro_accuracy(pred_cls: np.ndarray, labels: np.ndarray, seen: list[int]) -> float:
    accs = []
    for c in seen:
        m = np.asarray(labels) == c
        if not m.any():
            raise ValueError(f"missing validation class {c}")
        accs.append(float((np.asarray(pred_cls)[m] == c).mean()))
    return float(np.mean(accs))


