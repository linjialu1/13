def screen_promote(diffs: list[float]) -> dict:
    """Promotion rule: all three (11/22/33) validation diffs strictly > 0."""
    if len(diffs) != 3:
        raise ValueError("screening requires exactly 3 seeds")
    d = [float(x) for x in diffs]
    return {"diffs": d, "all_strictly_positive": bool(all(x > 0.0 for x in d)),
            "state": "PROMOTED" if all(x > 0.0 for x in d) else "SCREEN_FAIL"}


# ---------------------------------------------------------------- S4 statistics (fixed rules)
def average_ranks(values) -> np.ndarray:
    """Average ranks for ties (1-based)."""
    v = np.asarray(values, dtype=np.float64)
    order = np.argsort(v, kind="mergesort")
    ranks = np.empty(len(v), dtype=np.float64)
    i = 0
    while i < len(v):
        j = i
        while j + 1 < len(v) and v[order[j + 1]] == v[order[i]]:
            j += 1
        avg = (i + j) / 2.0 + 1.0
        for k in range(i, j + 1):
            ranks[order[k]] = avg
        i = j + 1
    return ranks


def spearman(x, y) -> dict:
    """Spearman rho with average ranks; constant input -> rho null, UNDEFINED_CONSTANT."""
    a = np.asarray(x, dtype=np.float64)
    b = np.asarray(y, dtype=np.float64)
    if a.size != b.size or a.size < 2:
        raise ValueError("spearman needs equal sizes >= 2")
    if np.all(a == a[0]) or np.all(b == b[0]):
        return {"rho": None, "n": int(a.size), "status": "UNDEFINED_CONSTANT"}
    ra, rb = average_ranks(a), average_ranks(b)
    ra = ra - ra.mean()
    rb = rb - rb.mean()
    denom = float(np.sqrt((ra ** 2).sum() * (rb ** 2).sum()))
    return {"rho": float((ra * rb).sum() / denom), "n": int(a.size), "status": "OK",
            "ties": int(len(a) - len(set(a.tolist())) + len(b) - len(set(b.tolist())))}


def holm(pvals: dict[str, float], family_size: int = 24) -> dict:
    """Holm step-down over the pre-registered family of `family_size` comparisons.

    p_adj(i) = min(1, max_{j<=i} [(family_size - j + 1) * p_(j)])
    Cells without 8 seeds must not be passed in (caller enforces null).
    """
    items = [(k, float(v)) for k, v in pvals.items() if v is not None]
    items.sort(key=lambda kv: kv[1])
    m = int(family_size)
    out, running = {}, 0.0
    for i, (k, p) in enumerate(items, start=1):
        running = max(running, (m - i + 1) * p)
        out[k] = {"raw_p": p, "adjusted_p": float(min(1.0, running))}
    omitted = [k for k, v in pvals.items() if v is None]
    return {"family_size": m, "results": out,
            "null_cells": omitted,
            "note": "null cells (no 8 seeds) carry no p-value and make no rejection claim"}


def paired_t_summary(diffs) -> dict:
    """Two-sided paired t (df = n-1) summary; degenerate cases handled explicitly."""
    d = np.asarray(diffs, dtype=np.float64)
    n = len(d)
    if n < 2:
        raise ValueError("paired t needs n >= 2")
    m = float(d.mean())
    sd = float(d.std(ddof=1))
    se = sd / float(np.sqrt(n))
    if sd == 0.0:
        if m == 0.0:
            return {"mean": 0.0, "sd": 0.0, "n": n, "t": None, "p": 1.0,
                    "state": "DEGENERATE_ZERO_DIFF"}
        return {"mean": m, "sd": 0.0, "n": n, "t": None, "p": 0.0,
                "state": "DEGENERATE_CONSTANT_NONZERO"}
    t = m / se
    try:
        from math import erf, sqrt
        # two-sided p via the regularized incomplete beta is not in stdlib; approximate
        # with the normal for df>=7 is NOT acceptable, so require scipy when available.
        from scipy import stats as _st
        p = float(2 * _st.t.sf(abs(t), df=n - 1))
    except Exception:
        p = None
    return {"mean": m, "sd": sd, "n": n, "t": float(t), "p": p, "state": "OK"}
